// The exam on ויקרא ט״ז (18.10.2026) and its preparation page — the
// teacher's draft (issue #7), created once as drafts hidden from students.
// From then on everything lives in the DB and she edits it on the page.
// The answer key is hers to check and approve.

const q = (id: string, points: number, text: string, answer: string, lines?: number) => ({
  id,
  points,
  text,
  answer,
  ...(lines != null ? { lines } : {}),
});

// the four discussion questions of the units, as worded on the site now
async function discussionList(): Promise<string> {
  const letters = ["א", "ב", "ג", "ד", "ה", "ו"];
  const out: string[] = [];
  for (const ref of DEFAULT_ARGUMENT_REFS) {
    const reg = TASK_REGISTRY[ref];
    if (!reg) continue;
    const c = await effectiveContent(reg.content);
    if (c.discussion?.question) out.push(`${letters[out.length]}. ${c.discussion.question}`);
  }
  return out.join("\n");
}

